/**
 * Editor bridge files.
 *
 * Three artifacts, all idempotent and rewritten only when their content changes:
 *
 * 1. `~/.acp-editor/bin/ue-mcp.cmd` + `~/.acp-editor/bin/ue-mcp.mjs` — a helper the
 *    agent can run through its shell. Agents always have a shell; not every agent can
 *    mount an MCP server (dsh 0.1.5 accepted the list and mounted nothing), so one
 *    command is the reliable common denominator.
 *    The script is **copied next to the shim** and located with `%~dp0`, so nothing in
 *    the shim depends on where the hub package was installed, and moving the repo does
 *    not break it. `node` comes from PATH; the hub's own executable is only a fallback.
 * 2. `~/.acp-editor/dsh-editor.patch.yml` — a dsh overlay that registers the editor MCP
 *    at profile level and appends the editor hint to the ACP profile's system prompt.
 *    Its text contains **no** template variables: dsh versions disagree about which ones
 *    a prompt section registers (0.1.5 accepts `{{cwd}}`, 0.2.2 fails every turn with
 *    "unknown prompt variable"), and a prompt that cannot render is worse than a vague one.
 * 3. Optional per-agent shims (`dsh.cmd`) for a runtime that is not a CLI, e.g. the dsh
 *    build bundled inside the desktop app.
 *
 * Every shim is self-tested before it is trusted: a broken bridge must not make the
 * agent believe a command exists.
 */
import { execFile } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { basename, join, resolve } from 'node:path';
import { promisify } from 'node:util';

const execFileAsync = promisify(execFile);

export interface EditorBridge {
  /** Directory put in front of the agent's PATH (and offered to the user's PATH). */
  binDir: string;
  shimPath: string;
  /** dsh `--patch` overlay that teaches the agent about the command. */
  patchPath: string;
  /** Environment for the agent process: PATH with `binDir` first. */
  env: Record<string, string>;
  /** Whether `ue-mcp.cmd` passed its own self-test. */
  shimWorks: boolean;
}

export interface EditorBridgeOptions {
  /** Repo script to run; defaults to `<repo>/scripts/ue-mcp.mjs`. */
  scriptPath?: string;
  /** Where the generated files live; defaults to `~/.acp-editor`. */
  root?: string;
  /** Editor MCP endpoint written into the overlay (the CLI defaults to the same). */
  url?: string;
}

const HINT = `      The Unreal editor for this project is running on this machine and exposes an
      MCP server (editor state, PIE control, logs, asset search, toolset gateway).
      If your tool list contains \`mcp__unreal__*\` tools, prefer them for editor work.
      If it does not — or when a single compact snapshot is all you need — a helper
      command is on PATH:
        ue-mcp context                    -- open assets, selected actors/assets, content-browser path, PIE, camera
        ue-mcp toolsets                   -- what the editor exposes
        ue-mcp tools <toolset>            -- tool names and their required arguments
        ue-mcp call <toolset> <tool> '{"k":1}'
      When the user says "this blueprint", "the current scene", "the selected actor"
      or otherwise refers to the editor, read the editor state FIRST (through those
      tools, or \`ue-mcp context\`) instead of guessing from files on disk. If neither
      reaches the editor, say the editor is not reachable rather than inventing state.`;

/** The dsh overlay: register the editor MCP, keep the cwd line, append the hint. */
export function dshPatchText(
  url = 'http://127.0.0.1:8000/mcp',
  options: { includeHint?: boolean } = {},
): string {
  const hint = options.includeHint === false ? '' : `\n${HINT}\n`;
  return `# Generated by acp-editor (scripts/ue-mcp.mjs). Safe to delete; it is recreated on demand.
#
# dsh's ACP mode ignores \`session/new.mcpServers\`, but a profile-level MCP entry does
# reach the agent's tool list (verified on 0.2.2-rc.1: mcp__unreal__* appears). The
# entry is registered here so the capability is part of every ACP session, and
# failOnStartupError stays false so a closed editor costs nothing.
- insert:
    - id: unreal-mcp
      name: '@deepseek-ai/dsh-mcp-client'
      config:
        transport: streamable-http
        serverName: unreal
        url: ${url}
        failOnStartupError: false
- id: system-prompt
  config:
    personaSuffix: |-
      The session's working directory is the project root — run \`pwd\` if you need it.
${hint}`;
}

/**
 * A portable `.cmd` that runs `<dir>\<script>`.
 *
 * `node` from PATH is the normal path — nothing recorded. The recorded executable is
 * only a fallback, and only when this hub *is* node (or Electron running as node), so
 * the value is always meaningful on the machine that wrote it. With no usable runtime
 * the shim fails loudly instead of running a stale path: the self-test then reports it
 * and the agent is never told the command exists.
 */
export function shimText(scriptName = 'ue-mcp.mjs', fallbackNode?: string): string {
  const electron = Boolean(process.versions.electron);
  const fallback =
    fallbackNode ?? (electron || process.release?.name === 'node' ? process.execPath : '');

  const lines = [
    '@echo off',
    'rem Generated by acp-editor on this machine. Runs a script that sits next to this file.',
    'setlocal',
    'where node >nul 2>nul',
    'if errorlevel 1 goto fallback',
    'node "%~dp0' + scriptName + '" %*',
    'exit /b %ERRORLEVEL%',
    ':fallback',
  ];

  if (fallback) {
    if (electron) lines.push('set "ELECTRON_RUN_AS_NODE=1"');
    lines.push(`set "NODE_EXE=${fallback}"`);
    lines.push('"%NODE_EXE%" "%~dp0' + scriptName + '" %*');
    lines.push('exit /b %ERRORLEVEL%');
  } else {
    lines.push(
      'echo ue-mcp: Node.js was not found on PATH; the editor MCP tools are still available. 1>&2',
    );
    lines.push('exit /b 127');
  }

  lines.push('');
  return lines.join('\r\n');
}

/** Shim that always uses the recorded entry (for runtimes that are not a CLI). */
export function entryShimText(entryPath: string, fallbackNode = process.execPath): string {
  const electron = Boolean(process.versions.electron);
  return [
    '@echo off',
    'rem Generated by acp-editor. Runs a fixed entry point with the hub runtime.',
    'setlocal',
    `if not exist "${entryPath}" (`,
    '  echo This agent runtime is missing on disk. Reopen the editor so acp-editor resolves it again. 1>&2',
    `  echo Missing: ${entryPath} 1>&2`,
    '  exit /b 127',
    ')',
    ...(electron ? ['set "ELECTRON_RUN_AS_NODE=1"'] : []),
    `"${fallbackNode}" "${entryPath}" %*`,
    '',
  ].join('\r\n');
}

async function writeIfChanged(path: string, content: string): Promise<boolean> {
  try {
    const current = await readFile(path, 'utf8');
    if (current === content) return false;
  } catch {
    /* missing: write it */
  }
  await mkdir(resolve(path, '..'), { recursive: true });
  await writeFile(path, content, 'utf8');
  return true;
}

/** Does the shim actually run? A broken bridge must not be advertised. */
export async function selfTestMethod(shimPath: string, args: string[]): Promise<boolean> {
  try {
    await execFileAsync(shimPath, args, { timeout: 15_000, windowsHide: true, shell: true });
    return true;
  } catch (err) {
    const stderr = String((err as { stderr?: string }).stderr ?? '').trim();
    console.warn(`[bridge] self-test failed for ${shimPath}: ${stderr || (err as Error).message}`);
    return false;
  }
}

const cache = new Map<string, Promise<EditorBridge>>();

/**
 * Materialise the bridge once per root and reuse it. Never throws: if the filesystem
 * refuses, the caller simply gets `null` and sessions still work.
 */
export async function ensureEditorBridge(options: EditorBridgeOptions = {}): Promise<EditorBridge | null> {
  const root = options.root ?? join(homedir(), '.acp-editor');
  const scriptPath = options.scriptPath ?? resolve(import.meta.dirname, '../../../scripts/ue-mcp.mjs');
  const key = `${root}|${scriptPath}|${options.url ?? ''}`;
  const existing = cache.get(key);
  if (existing) return existing;

  const task = (async (): Promise<EditorBridge> => {
    const binDir = join(root, 'bin');
    const localScript = join(binDir, basename(scriptPath));
    const shimPath = join(binDir, 'ue-mcp.cmd');
    const patchPath = join(root, 'dsh-editor.patch.yml');

    // Ship the script beside the shim: `%~dp0` then resolves it, so the shim survives
    // a moved repo and needs no install path baked in.
    await writeIfChanged(localScript, await readFile(scriptPath, 'utf8'));
    await writeIfChanged(shimPath, shimText(basename(scriptPath)));

    const shimWorks = await selfTestMethod(shimPath, ['--help']);
    // The hint is only written when the command actually runs; a broken bridge must
    // never make the agent believe it exists. The MCP registration stays either way.
    await writeIfChanged(patchPath, dshPatchText(options.url, { includeHint: shimWorks }));
    if (!shimWorks) {
      console.warn(
        '[bridge] ue-mcp is not usable on this machine; the agent will only be told about MCP.',
      );
    }

    // Windows environments usually spell it `Path`; adding a second `PATH` key would
    // give CreateProcess two entries and the winner is undefined.
    const pathKey = Object.keys(process.env).find((entry) => entry.toUpperCase() === 'PATH') ?? 'PATH';
    const env = { [pathKey]: `${binDir};${process.env[pathKey] ?? ''}` };
    return { binDir, shimPath, patchPath, env, shimWorks };
  })();

  cache.set(key, task);
  try {
    return await task;
  } catch {
    cache.delete(key);
    return null;
  }
}

/**
 * Write (and verify) a shim for an agent whose runtime is not a CLI on PATH, e.g. the
 * dsh build bundled inside the desktop app. Returns null when it does not run.
 */
export async function ensureAgentShim(
  name: string,
  entryPath: string,
  binDir: string,
  versionArgs: string[] = ['--version'],
): Promise<string | null> {
  if (!/\.(?:c|m)?js$/i.test(entryPath)) return null;
  const shim = join(binDir, `${name}.cmd`);
  await writeIfChanged(shim, entryShimText(entryPath));
  return (await selfTestMethod(shim, versionArgs)) ? shim : null;
}

/** Tests only. */
export function resetEditorBridgeCache(): void {
  cache.clear();
}

/**
 * Make `binDir` visible to the user's own shells (the agent process gets it via env,
 * a human typing `dsh` or `ue-mcp` does not). Idempotent; writes HKCU\Environment as
 * REG_EXPAND_SZ while preserving other entries untouched (`DoNotExpandEnvironmentNames`
 * keeps `%VAR%` entries from being expanded and destroyed).
 */
export async function ensureUserPathEntry(dir: string): Promise<boolean> {
  if (process.platform !== 'win32') return false;
  const script = [
    "$dir = $env:ACP_PATH_ENTRY",
    'if ([string]::IsNullOrWhiteSpace($dir)) { exit 2 }',
    "$key = Get-Item 'HKCU:\\Environment'",
    "$current = $key.GetValue('Path', '', 'DoNotExpandEnvironmentNames')",
    "$parts = @($current -split ';' | Where-Object { $_ -ne '' })",
    'if ($parts -contains $dir) { exit 0 }',
    "$next = (@($parts) + $dir) -join ';'",
    "Set-ItemProperty -Path 'HKCU:\\Environment' -Name Path -Value $next -Type ExpandString",
    'exit 3',
  ].join('\r\n');
  try {
    await execFileAsync('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', script], {
      timeout: 20_000,
      windowsHide: true,
      env: { ...process.env, ACP_PATH_ENTRY: dir },
    });
    return false; // exit 0: already present
  } catch (err) {
    if ((err as { code?: number }).code === 3) return true; // added
    console.warn(`[bridge] could not add ${dir} to the user PATH: ${(err as Error).message}`);
    return false;
  }
}
